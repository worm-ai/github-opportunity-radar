// Read-only by default. RADAR_DECISION_REVISE=1 saves one revision of the existing assistant note.
import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';

const base = 'http://127.0.0.1:4318';
const runId = 'd79a1f02-17c8-4d6d-bf02-1be4e122452f';
const output = '.data/browser/demand-decisions';
const title = 'agent-world 服务入口已接通，状态一致性未通过';
const conclusion = '在没有 Godot 硬约束的假设下，保留 agent-world 单项目有界验证，暂不推荐直接采用。此前串行核心 30 tick 实验通过；本轮真实 MCP、WebSocket/HTTP 和新进程读取显示，原版动作返回成功却未保存，此前改造版直接接异步工具则报错，注册失败还留下内存成员。接通协议不能证明服务可用，必须先补状态写入和失败边界。此结论限本地单循环启动器与本轮依赖，不代表所有上游部署；没有外部 LLM、完整玩家流程或独立收益证据。';
const nextAction = '先做有界服务状态协调验证：注册、动作、tick、检查点使用明确的写入路径，失败撤销内存及数据库变化，成功后再发布观察状态。覆盖真实事件等待、context、动作、WebSocket/HTTP 和新进程恢复，再加两客户端及注册/保存失败反例；不关闭 Django 异步保护，不把任意线程调用当作修复。此前协议探针和 30 tick 核心实验已完成，不重复列为待办。若需重做大部分核心则暂停并重比候选成本；现阶段不引入第二套世界状态。持续代理、玩家干预、长期稳定性及用户收益仍待验证。';
mkdirSync(output, { recursive: true });
async function get(path) { const r = await fetch(`${base}/api/v1/${path}`); assert.equal(r.status, 200, path); return r.json(); }
const [before, archive, materials, notesBefore] = await Promise.all([get(`demands/${runId}`), get('experiments'), get(`demands/${runId}/note-sources`), get('research-notes')]);
const record = archive.records.find(item => item.id === 'agent-world-service-2026-10-23');
assert.ok(record, 'The completed service probe must exist');
const evidence = materials.sources.find(item => item.ref.kind === 'experiment' && item.ref.experimentId === record.id);
assert.ok(evidence); assert.ok(evidence.text.includes(record.conclusion));
assert.ok(record.conclusion.length >= 16 && record.conclusion.length <= 2000);
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const errors = [], writes = [], cases = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (!['GET', 'HEAD', 'OPTIONS'].includes(request.method())) writes.push({ method: request.method(), url: request.url() }); });
let saved;
try {
  await page.goto(`${base}/research?run=${runId}`);
  const region = page.getByRole('region', { name: '本次选型判断', exact: true });
  await region.waitFor();
  saved = notesBefore.find(note => note.originDemandId === runId && note.title === title && note.author === 'assistant' && !note.supersededBy);
  if (!saved) {
    assert.equal(process.env.RADAR_DECISION_REVISE, '1', 'No current decision found; default verification is read-only. Explicit RADAR_DECISION_REVISE=1 is required to revise the prior note.');
    const previous = notesBefore.find(note => note.id === 'e737f666-6da1-4b45-bc4d-9b538d130d50' && !note.supersededBy && note.author === 'assistant' && note.originDemandId === runId);
    assert.ok(previous, 'Expected active predecessor; do not create an unrelated or duplicate decision');
    await region.locator(`[data-note-id="${previous.id}"]`).getByRole('button', { name: '修订此判断', exact: true }).click();
    await region.getByRole('textbox', { name: '判断标题', exact: true }).fill(title);
    await region.getByLabel('研究决定', { exact: true }).selectOption('continue');
    await region.getByLabel('判断记录者', { exact: true }).selectOption('assistant');
    await region.getByRole('textbox', { name: '判断结论', exact: true }).fill(conclusion);
    await region.getByRole('textbox', { name: '判断下一步', exact: true }).fill(nextAction);
    await region.getByLabel('判断来源 1', { exact: true }).selectOption(evidence.key);
    await region.getByRole('textbox', { name: '判断引用 1', exact: true }).fill('这是一段不存在于原始实验记录中的伪造引文，用于确认保存会被阻止。');
    assert.equal(await region.getByRole('button', { name: '保存研究判断', exact: true }).isDisabled(), true);
    await region.getByText('这段引用不在所选原文中，请核对。', { exact: true }).waitFor();
    cases.push('fabricated quotation is blocked before saving');
    await region.getByRole('textbox', { name: '判断引用 1', exact: true }).fill(record.conclusion);
    const responsePromise = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/v1/research-notes'));
    await region.getByRole('button', { name: '保存研究判断', exact: true }).click();
    const response = await responsePromise; assert.equal(response.status(), 201);
    saved = await response.json();
    assert.equal(writes.length, 1);
    assert.equal(saved.supersedesId, previous.id);
    const notesAfter = await get('research-notes');
    assert.equal(notesAfter.find(note => note.id === previous.id).supersededBy, saved.id);
    cases.push('actual assistant decision revised once with service counterevidence; original retained');
  } else cases.push('existing assistant self-use record reused without another write');
  assert.equal(saved.originDemandId, runId); assert.equal(saved.author, 'assistant');
  assert.equal(saved.nextAction, nextAction); assert.equal(saved.evidence[0].quote, record.conclusion);
  assert.deepEqual(saved.evidenceStates, ['same']);
  assert.ok(saved.evidence[0].notice.includes(record.limitations[0]));
  assert.ok(saved.evidence[0].notice.includes(record.sources[0].modification.sha256));
  await page.reload();
  const card = region.locator(`[data-note-id="${saved.id}"]`);
  await card.getByRole('heading', { name: title, exact: true }).waitFor();
  await card.getByText(/代理研究 · 待人工复核/).waitFor();
  await card.getByText(nextAction, { exact: false }).waitFor();
  const downloadEvent = page.waitForEvent('download');
  await card.getByRole('link', { name: '导出判断', exact: true }).click();
  const download = await downloadEvent; await download.saveAs(`${output}/decision.md`);
  const report = readFileSync(`${output}/decision.md`, 'utf8');
  assert.ok(report.includes(runId)); assert.ok(report.includes('代理研究，待人工复核'));
  assert.ok(report.includes(record.conclusion)); assert.ok(report.includes(record.sources[0].commit));
  cases.push('refresh retains the actual decision; download includes origin, exact quote, commit and limits');
  for (const [name, width, height] of [['desktop', 1440, 1000], ['mobile', 390, 844]]) {
    await page.setViewportSize({ width, height }); await card.scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: `${output}/${name}.png` });
  }
  await card.getByRole('button', { name: '修订此判断', exact: true }).click();
  assert.equal(new URL(page.url()).searchParams.get('note'), saved.id);
  await page.reload();
  assert.equal(await region.getByRole('textbox', { name: '判断结论', exact: true }).inputValue(), conclusion);
  assert.equal(await region.getByRole('textbox', { name: '判断下一步', exact: true }).inputValue(), nextAction);
  cases.push('revision deep link reloads saved values without writing or replacing earlier evidence');
  await page.goto(`${base}/opportunities#research-notes`);
  const notebook = page.getByRole('region', { name: '研究判断记录', exact: true });
  await notebook.getByRole('heading', { name: title, exact: true }).waitFor();
  const notebookCard = notebook.locator(`[data-note-id="${saved.id}"]`);
  await notebookCard.getByRole('link', { name: '更新判断', exact: true }).click();
  await page.waitForURL(`**/research?run=${runId}&note=${saved.id}#demand-decisions`);
  await region.getByRole('textbox', { name: '判断结论', exact: true }).waitFor();
  cases.push('existing notebook returns to this exact demand rather than the combination-research form');
  const postsBeforeFixture = writes.length;
  await page.route('**/api/v1/demands/features', route => route.fulfill({ json: { sourceStudy: true, sourceResume: true } }));
  await page.reload(); await page.getByRole('button', { name: '编辑需求 / 重试', exact: true }).waitFor();
  assert.equal(await region.count(), 0);
  cases.push('older backend does not expose an unsupported write form');
  assert.equal(writes.length, postsBeforeFixture);
  assert.deepEqual(await get(`demands/${runId}`), before);
  assert.equal(errors.length, 0, errors.join('\n'));
  assert.ok(writes.every(request => request.url.endsWith('/api/v1/research-notes')));
  if (process.env.RADAR_DECISION_REVISE !== '1') assert.equal(writes.length, 0, 'Default checks must never write');
  writeFileSync(`${output}/verification.json`, JSON.stringify({ verifiedAt: new Date().toISOString(), runId, noteId: saved.id, origin: 'Actual assistant self-use on the user-provided scenario, not independent user benefit evidence', cases, errors, writes, originalDemandUnchanged: true }, null, 2));
  console.log(JSON.stringify({ output, noteId: saved.id, cases, writes: writes.length, errors }));
} finally { await context.close(); await browser.close(); }
