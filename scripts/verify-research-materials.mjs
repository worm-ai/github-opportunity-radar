// Reads real research materials; never submits a paid analysis or writes validation evidence.
import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
import { chromium } from "@playwright/test";

const base = process.env.RADAR_BROWSER_URL || "http://127.0.0.1:4317";
const projects = await (await fetch(`${base}/api/v1/projects`)).json();
const before = await (await fetch(`${base}/api/v1/analysis/runs`)).json();
const project = projects.find((item) => item.fullName === "storytold/photocraft") ?? projects.find((item) => item.issues?.some((issue) => issue.bodyExcerpt));
assert.ok(project, "An actual collected issue is required to verify the flow");
const issue = project.issues.find((item) => item.number === 7734) ?? project.issues.find((item) => item.bodyExcerpt);
const second = projects.find((item) => item.fullName === "phucnguyentvp1/frameweaver") ?? projects.find((item) => item.id !== project.id);
const browser = await chromium.launch({ channel: "msedge", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
const errors = [], writes = [];
page.on("pageerror", (error) => errors.push(error.message));
page.on("request", (request) => { if (!["GET", "HEAD"].includes(request.method())) writes.push(request.url()); });
mkdirSync(".data/browser", { recursive: true });
try {
  await page.goto(`${base}/projects/${project.id}`);
  const card = page.locator(".issue-card").filter({ hasText: issue.title });
  await card.locator("summary").click();
  await card.getByRole("link", { name: "围绕此问题研究组合" }).click();
  const form = page.getByRole("region", { name: "定向研究", exact: true });
  const originSelect = form.getByRole("combobox", { name: "研究问题起点" });
  await originSelect.locator(`option[value="${project.id}:${issue.number}"]`).waitFor({ state: "attached" });
  assert.equal(await originSelect.inputValue(), `${project.id}:${issue.number}`);
  await form.getByRole("combobox", { name: "研究组件 2" }).selectOption(second.id);
  const material = form.getByRole("region", { name: "组合研究材料", exact: true });
  assert.equal(await material.locator(".research-material").count(), 2);
  const origin = material.getByRole("article", { name: "选定的问题原文" });
  assert.equal(await origin.locator(":scope > pre").textContent(), issue.bodyExcerpt);
  assert.equal(await origin.getByRole("link", { name: "核对当前讨论" }).getAttribute("href"), issue.url);
  assert.ok((await origin.innerText()).includes(issue.authorAssociation));
  await origin.getByRole("button", { name: "用此问题起草研究问题" }).click();
  const question = form.getByRole("textbox", { name: "待证伪的研究问题" });
  assert.ok((await question.inputValue()).includes(issue.title.slice(0, 240)));
  assert.ok((await question.inputValue()).includes("是否只需修复单个项目"));
  for (const detail of await material.locator(".research-material details").all()) await detail.locator("summary").click();
  await page.screenshot({ path: ".data/browser/research-materials-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: ".data/browser/research-materials-mobile.png", fullPage: true });
  await form.getByRole("combobox", { name: "研究组件 1" }).selectOption("");
  assert.equal(await originSelect.inputValue(), "");
  assert.equal(await material.locator(".research-origin").count(), 0, "Removing the origin project must clear its issue binding");
  await page.goto(`${base}/opportunities?project=${project.id}&project=${second.id}&issue=999999999`);
  await form.getByText("原问题不在当前样本中。", { exact: false }).waitFor();
  await question.fill("An invalid issue link must not silently become an ungrounded research request.");
  assert.equal(await form.getByRole("button", { name: "研究这个组合", exact: true }).isDisabled(), true);
  await originSelect.selectOption("");
  assert.equal(await form.getByText("原问题不在当前样本中。", { exact: false }).count(), 0);
  const after = await (await page.request.get(`${base}/api/v1/analysis/runs`)).json();
  assert.deepEqual(after.map((run) => run.id), before.map((run) => run.id));
  assert.deepEqual(writes, []);
  assert.deepEqual(errors, []);
  const result = { browser: "Edge", sourceProject: project.fullName, sourceIssue: issue.number, comparedWith: second.fullName, sourceQuote: "exact", questionDraft: "passed", clearedRemovedOrigin: "passed", invalidOriginBlocked: "passed", mobileOverflow: false, paidCalls: "none", writes, errors };
  writeFileSync(".data/browser/research-materials-verification.json", JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
} finally { await browser.close(); }
